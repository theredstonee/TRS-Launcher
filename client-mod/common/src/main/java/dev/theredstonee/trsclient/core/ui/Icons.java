	private static void put(String id, String... rows) {
		ICONS.put(id, rows);
	}

	/** Alle bekannten Symbol-IDs. */
	public static Set<String> ids() {
		return ICONS.keySet();
	}

	public static boolean has(String id) {
		return id != null && ICONS.containsKey(id);
	}

	/** Zeilen eines Symbols oder null. */
	public static String[] rows(String id) {
		return id == null ? null : ICONS.get(id);
	}

	/**
	 * Zeichnet ein Symbol mit {@code px} Pixeln je Punkt (8×{@code px} groß).
	 * Unbekannte IDs zeichnen nichts.
	 */
	public static void draw(Canvas c, String id, int x, int y, int px, int argb) {
		String[] rows = rows(id);
		if (rows == null || px <= 0) return;
		for (int row = 0; row < rows.length; row++) {
			String line = rows[row];
			int col = 0;
			while (col < line.length()) {
				if (line.charAt(col) != '#') {
					col++;
					continue;
				}
				int end = col;
				while (end < line.length() && line.charAt(end) == '#') end++;
				c.fill(x + col * px, y + row * px, x + end * px, y + (row + 1) * px, argb);
				col = end;
			}
		}
	}
