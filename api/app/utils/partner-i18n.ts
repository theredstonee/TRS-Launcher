/** Pfad der Partner-Seite (Popup). */
export function partnerPath(slug: string): string {
  return `/partners/${encodeURIComponent(slug)}`
}

/** Text in der Seitensprache (Spanisch → Englisch), leer → die andere Sprache. */
export function partnerText(text: { de: string, en: string }, lang: Lang): string {
  const first = lang === 'de' ? text.de : text.en
  return first.trim() ? first : (lang === 'de' ? text.en : text.de)
}

/** Kurzzeichen für Partner ohne Logo. */
export function partnerInitials(name: string): string {
  const parts = name.replace(/[^\p{L}\p{N} ]/gu, ' ').trim().split(/\s+/).filter(Boolean)
  const s = parts.length > 1 ? `${parts[0]![0]}${parts[1]![0]}` : (parts[0] ?? '?').slice(0, 2)
  return s.toUpperCase()
}
