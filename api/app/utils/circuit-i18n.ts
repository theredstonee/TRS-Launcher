export const circuitTexts: Record<Lang, CircuitTexts> = { en, de, es }

/** Text einer Schaltung in der Seitensprache (sonst Englisch, sonst erste vorhandene Sprache). */
export function circuitText(texts: Record<string, { name?: string, desc?: string, note?: string }> | undefined, lang: string, key: 'name' | 'desc' | 'note'): string {
  if (!texts) return ''
  return texts[lang]?.[key] ?? texts.en?.[key] ?? Object.values(texts).find((t) => t[key])?.[key] ?? ''
}
