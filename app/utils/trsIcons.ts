export type TrsIconId = keyof typeof TRS_ICONS

export const TRS_ICON_IDS = Object.keys(TRS_ICONS) as TrsIconId[]

/** Text-Zeichnung → Raster (unbekannte Zeichen = durchsichtig). */
export function trsIconGrid(id: string): PixelGrid | null {
  const art = (TRS_ICONS as Record<string, string[] | undefined>)[id]
  if (!art) return null
  const grid = emptyGrid(16)
  art.forEach((line, y) => {
    for (let x = 0; x < 16; x++) {
      const color = TRS_ICON_COLORS[line[x] ?? '.']
      if (color) grid.px[y * 16 + x] = hexToPx(color)
    }
  })
  return grid
}
