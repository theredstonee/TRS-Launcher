const E = '................'

/** Inhalt mittig in 16 Zeilen setzen (`top` = Leerzeilen davor). */
function rows(top: number, lines: string[], shift = 0): string[] {
  const shifted = lines.map((l) => (shift > 0 ? '.'.repeat(shift) + l.slice(0, 16 - shift) : shift < 0 ? l.slice(-shift) + '.'.repeat(-shift) : l))
  const out = [...Array<string>(top).fill(E), ...shifted]
  while (out.length < 16) out.push(E)
  return out
}

